package com.example.engine

import com.example.model.*
import java.text.SimpleDateFormat
import java.util.*
import kotlin.math.*

object LaserGCodeGenerator {

  data class ToolpathPlan(
    val gcode: String,
    val simulation: SimulationResult
  )

  fun generate(
    shapes: List<LaserShape>,
    layers: List<LaserLayer>,
    bedWidthMm: Float = 400f,
    bedHeightMm: Float = 400f
  ): ToolpathPlan {
    val layerMap = layers.associateBy { it.id }
    val gcodeLines = mutableListOf<String>()
    val segments = mutableListOf<ToolpathSegment>()

    val sdf = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.US)
    val now = sdf.format(Date())

    // G-Code Header
    gcodeLines.add("; ===========================================")
    gcodeLines.add("; Generated by LightBurn Laser Studio")
    gcodeLines.add("; Date: $now")
    gcodeLines.add("; Bed: ${bedWidthMm.toInt()}x${bedHeightMm.toInt()} mm")
    gcodeLines.add("; ===========================================")
    gcodeLines.add("G21          ; Set units to millimeters")
    gcodeLines.add("G90          ; Absolute coordinates")
    gcodeLines.add("M05          ; Ensure laser is OFF")
    gcodeLines.add("G0 Z0.000    ; Default focus height")

    var currentX = 0f
    var currentY = 0f
    var totalCutDist = 0f
    var totalRapidDist = 0f
    var totalDurationSec = 0.0

    var minX = Float.MAX_VALUE
    var minY = Float.MAX_VALUE
    var maxX = Float.MIN_VALUE
    var maxY = Float.MIN_VALUE

    // Process layer by layer in defined layer order
    for (layer in layers) {
      if (!layer.outputEnabled) continue
      val layerShapes = shapes.filter { it.layerId == layer.id }
      if (layerShapes.isEmpty()) continue

      gcodeLines.add("")
      gcodeLines.add("; -------------------------------------------")
      gcodeLines.add("; LAYER: ${layer.name} [${layer.mode.label}]")
      gcodeLines.add("; Speed: ${layer.speedMmMin.toInt()} mm/min | Max Power: ${layer.powerMaxPercent}% | Passes: ${layer.passes}")
      gcodeLines.add("; -------------------------------------------")

      if (layer.airAssist) {
        gcodeLines.add("M08          ; Air Assist ON")
      }

      val maxSValue = (layer.powerMaxPercent / 100f * 1000).roundToInt().coerceIn(1, 1000)

      for (pass in 1..layer.passes) {
        if (layer.passes > 1) {
          gcodeLines.add("; Pass $pass of ${layer.passes}")
        }

        for (shape in layerShapes) {
          // Track overall bounds
          minX = min(minX, shape.x)
          minY = min(minY, shape.y)
          maxX = max(maxX, shape.x + shape.width)
          maxY = max(maxY, shape.y + shape.height)

          when (layer.mode) {
            LaserMode.LINE -> {
              val contours = getContoursForShape(shape)
              for (contour in contours) {
                if (contour.size < 2) continue

                val start = contour.first()
                // Rapid travel to start
                if (currentX != start.first || currentY != start.second) {
                  gcodeLines.add(String.format(Locale.US, "G0 X%.3f Y%.3f", start.first, start.second))
                  val rapidSeg = ToolpathSegment(
                    startX = currentX,
                    startY = currentY,
                    endX = start.first,
                    endY = start.second,
                    isRapid = true,
                    powerPercent = 0f,
                    speedMmMin = 6000.0,
                    layerColor = layer.color,
                    layerId = layer.id,
                    passIndex = pass
                  )
                  segments.add(rapidSeg)
                  totalRapidDist += rapidSeg.lengthMm
                  totalDurationSec += rapidSeg.durationSeconds
                  currentX = start.first
                  currentY = start.second
                }

                // Laser ON
                gcodeLines.add(String.format(Locale.US, "M03 S%d", maxSValue))

                // Trace path
                for (i in 1 until contour.size) {
                  val pt = contour[i]
                  gcodeLines.add(String.format(Locale.US, "G1 X%.3f Y%.3f F%.0f", pt.first, pt.second, layer.speedMmMin))
                  val cutSeg = ToolpathSegment(
                    startX = currentX,
                    startY = currentY,
                    endX = pt.first,
                    endY = pt.second,
                    isRapid = false,
                    powerPercent = layer.powerMaxPercent,
                    speedMmMin = layer.speedMmMin,
                    layerColor = layer.color,
                    layerId = layer.id,
                    passIndex = pass
                  )
                  segments.add(cutSeg)
                  totalCutDist += cutSeg.lengthMm
                  totalDurationSec += cutSeg.durationSeconds
                  currentX = pt.first
                  currentY = pt.second
                }

                // Laser OFF after contour
                gcodeLines.add("M05          ; Laser OFF")
              }
            }

            LaserMode.FILL -> {
              val scanlines = generateRasterScanlines(shape, layer.lineIntervalMm)
              for (line in scanlines) {
                // Rapid to scanline start
                if (currentX != line.startX || currentY != line.startY) {
                  gcodeLines.add(String.format(Locale.US, "G0 X%.3f Y%.3f", line.startX, line.startY))
                  val rapidSeg = ToolpathSegment(
                    startX = currentX,
                    startY = currentY,
                    endX = line.startX,
                    endY = line.startY,
                    isRapid = true,
                    powerPercent = 0f,
                    speedMmMin = 6000.0,
                    layerColor = layer.color,
                    layerId = layer.id,
                    passIndex = pass
                  )
                  segments.add(rapidSeg)
                  totalRapidDist += rapidSeg.lengthMm
                  totalDurationSec += rapidSeg.durationSeconds
                  currentX = line.startX
                  currentY = line.startY
                }

                // Laser burn stroke
                gcodeLines.add(String.format(Locale.US, "G1 X%.3f Y%.3f S%d F%.0f", line.endX, line.endY, maxSValue, layer.speedMmMin))
                val burnSeg = ToolpathSegment(
                  startX = currentX,
                  startY = currentY,
                  endX = line.endX,
                  endY = line.endY,
                  isRapid = false,
                  powerPercent = layer.powerMaxPercent,
                  speedMmMin = layer.speedMmMin,
                  layerColor = layer.color,
                  layerId = layer.id,
                  passIndex = pass
                )
                segments.add(burnSeg)
                totalCutDist += burnSeg.lengthMm
                totalDurationSec += burnSeg.durationSeconds
                currentX = line.endX
                currentY = line.endY
              }
              gcodeLines.add("M05          ; Laser OFF")
            }

            LaserMode.FILL_AND_LINE -> {
              // 1. Raster fill first
              val scanlines = generateRasterScanlines(shape, layer.lineIntervalMm)
              for (line in scanlines) {
                if (currentX != line.startX || currentY != line.startY) {
                  gcodeLines.add(String.format(Locale.US, "G0 X%.3f Y%.3f", line.startX, line.startY))
                  val rapidSeg = ToolpathSegment(
                    startX = currentX,
                    startY = currentY,
                    endX = line.startX,
                    endY = line.startY,
                    isRapid = true,
                    powerPercent = 0f,
                    speedMmMin = 6000.0,
                    layerColor = layer.color,
                    layerId = layer.id,
                    passIndex = pass
                  )
                  segments.add(rapidSeg)
                  totalRapidDist += rapidSeg.lengthMm
                  totalDurationSec += rapidSeg.durationSeconds
                  currentX = line.startX
                  currentY = line.startY
                }
                gcodeLines.add(String.format(Locale.US, "G1 X%.3f Y%.3f S%d F%.0f", line.endX, line.endY, maxSValue, layer.speedMmMin))
                val burnSeg = ToolpathSegment(
                  startX = currentX,
                  startY = currentY,
                  endX = line.endX,
                  endY = line.endY,
                  isRapid = false,
                  powerPercent = layer.powerMaxPercent,
                  speedMmMin = layer.speedMmMin,
                  layerColor = layer.color,
                  layerId = layer.id,
                  passIndex = pass
                )
                segments.add(burnSeg)
                totalCutDist += burnSeg.lengthMm
                totalDurationSec += burnSeg.durationSeconds
                currentX = line.endX
                currentY = line.endY
              }
              gcodeLines.add("M05          ; Laser OFF")

              // 2. Perimeter Line Cut
              val contours = getContoursForShape(shape)
              for (contour in contours) {
                if (contour.size < 2) continue
                val start = contour.first()
                if (currentX != start.first || currentY != start.second) {
                  gcodeLines.add(String.format(Locale.US, "G0 X%.3f Y%.3f", start.first, start.second))
                  val rapidSeg = ToolpathSegment(
                    startX = currentX,
                    startY = currentY,
                    endX = start.first,
                    endY = start.second,
                    isRapid = true,
                    powerPercent = 0f,
                    speedMmMin = 6000.0,
                    layerColor = layer.color,
                    layerId = layer.id,
                    passIndex = pass
                  )
                  segments.add(rapidSeg)
                  totalRapidDist += rapidSeg.lengthMm
                  totalDurationSec += rapidSeg.durationSeconds
                  currentX = start.first
                  currentY = start.second
                }
                gcodeLines.add(String.format(Locale.US, "M03 S%d", maxSValue))
                for (i in 1 until contour.size) {
                  val pt = contour[i]
                  gcodeLines.add(String.format(Locale.US, "G1 X%.3f Y%.3f F%.0f", pt.first, pt.second, layer.speedMmMin * 0.8))
                  val cutSeg = ToolpathSegment(
                    startX = currentX,
                    startY = currentY,
                    endX = pt.first,
                    endY = pt.second,
                    isRapid = false,
                    powerPercent = layer.powerMaxPercent,
                    speedMmMin = layer.speedMmMin * 0.8,
                    layerColor = layer.color,
                    layerId = layer.id,
                    passIndex = pass
                  )
                  segments.add(cutSeg)
                  totalCutDist += cutSeg.lengthMm
                  totalDurationSec += cutSeg.durationSeconds
                  currentX = pt.first
                  currentY = pt.second
                }
                gcodeLines.add("M05          ; Laser OFF")
              }
            }

            LaserMode.OFFSET_FILL -> {
              // Concentric inwards paths
              val offsets = generateOffsetContours(shape, 3)
              for (contour in offsets) {
                if (contour.size < 2) continue
                val start = contour.first()
                if (currentX != start.first || currentY != start.second) {
                  gcodeLines.add(String.format(Locale.US, "G0 X%.3f Y%.3f", start.first, start.second))
                  val rapidSeg = ToolpathSegment(
                    startX = currentX,
                    startY = currentY,
                    endX = start.first,
                    endY = start.second,
                    isRapid = true,
                    powerPercent = 0f,
                    speedMmMin = 6000.0,
                    layerColor = layer.color,
                    layerId = layer.id,
                    passIndex = pass
                  )
                  segments.add(rapidSeg)
                  totalRapidDist += rapidSeg.lengthMm
                  totalDurationSec += rapidSeg.durationSeconds
                  currentX = start.first
                  currentY = start.second
                }
                gcodeLines.add(String.format(Locale.US, "M03 S%d", maxSValue))
                for (i in 1 until contour.size) {
                  val pt = contour[i]
                  gcodeLines.add(String.format(Locale.US, "G1 X%.3f Y%.3f F%.0f", pt.first, pt.second, layer.speedMmMin))
                  val cutSeg = ToolpathSegment(
                    startX = currentX,
                    startY = currentY,
                    endX = pt.first,
                    endY = pt.second,
                    isRapid = false,
                    powerPercent = layer.powerMaxPercent,
                    speedMmMin = layer.speedMmMin,
                    layerColor = layer.color,
                    layerId = layer.id,
                    passIndex = pass
                  )
                  segments.add(cutSeg)
                  totalCutDist += cutSeg.lengthMm
                  totalDurationSec += cutSeg.durationSeconds
                  currentX = pt.first
                  currentY = pt.second
                }
                gcodeLines.add("M05          ; Laser OFF")
              }
            }
          }
        }
      }

      if (layer.airAssist) {
        gcodeLines.add("M09          ; Air Assist OFF")
      }
    }

    // G-Code Footer
    gcodeLines.add("")
    gcodeLines.add("; ===========================================")
    gcodeLines.add("; End of Program")
    gcodeLines.add("M05          ; Ensure laser is OFF")
    gcodeLines.add("M09          ; Air assist OFF")
    gcodeLines.add("G0 X0.000 Y0.000 ; Return to Work Origin")
    gcodeLines.add("M02          ; Program End")

    if (minX == Float.MAX_VALUE) {
      minX = 0f
      minY = 0f
      maxX = 0f
      maxY = 0f
    }

    val simulation = SimulationResult(
      segments = segments,
      totalCutDistanceMm = totalCutDist,
      totalRapidDistanceMm = totalRapidDist,
      totalDurationSeconds = totalDurationSec,
      boundsMinX = minX,
      boundsMinY = minY,
      boundsMaxX = maxX,
      boundsMaxY = maxY
    )

    return ToolpathPlan(
      gcode = gcodeLines.joinToString("\n"),
      simulation = simulation
    )
  }

  /**
   * Evaluates closed polyline contours for vector cutting
   */
  fun getContoursForShape(shape: LaserShape): List<List<Pair<Float, Float>>> {
    val contours = mutableListOf<List<Pair<Float, Float>>>()
    val x = shape.x
    val y = shape.y
    val w = shape.width
    val h = shape.height

    when (shape.type) {
      ShapeType.RECTANGLE -> {
        val r = shape.cornerRadius.coerceAtMost(min(w, h) / 2f)
        if (r <= 0f) {
          contours.add(listOf(
            Pair(x, y),
            Pair(x + w, y),
            Pair(x + w, y + h),
            Pair(x, y + h),
            Pair(x, y)
          ))
        } else {
          // Rounded rectangle contour
          val pts = mutableListOf<Pair<Float, Float>>()
          val steps = 8
          // Top edge
          pts.add(Pair(x + r, y))
          pts.add(Pair(x + w - r, y))
          // Top-right corner
          for (i in 0..steps) {
            val a = -PI.toFloat() / 2f + (PI.toFloat() / 2f) * (i / steps.toFloat())
            pts.add(Pair(x + w - r + r * cos(a), y + r + r * sin(a)))
          }
          // Right edge
          pts.add(Pair(x + w, y + h - r))
          // Bottom-right corner
          for (i in 0..steps) {
            val a = 0f + (PI.toFloat() / 2f) * (i / steps.toFloat())
            pts.add(Pair(x + w - r + r * cos(a), y + h - r + r * sin(a)))
          }
          // Bottom edge
          pts.add(Pair(x + r, y + h))
          // Bottom-left corner
          for (i in 0..steps) {
            val a = PI.toFloat() / 2f + (PI.toFloat() / 2f) * (i / steps.toFloat())
            pts.add(Pair(x + r + r * cos(a), y + h - r + r * sin(a)))
          }
          // Left edge
          pts.add(Pair(x, y + r))
          // Top-left corner
          for (i in 0..steps) {
            val a = PI.toFloat() + (PI.toFloat() / 2f) * (i / steps.toFloat())
            pts.add(Pair(x + r + r * cos(a), y + r + r * sin(a)))
          }
          pts.add(Pair(x + r, y))
          contours.add(pts)
        }
      }

      ShapeType.CIRCLE -> {
        val cx = x + w / 2f
        val cy = y + h / 2f
        val rx = w / 2f
        val ry = h / 2f
        val steps = 36
        val pts = mutableListOf<Pair<Float, Float>>()
        for (i in 0..steps) {
          val theta = (2 * PI * i / steps).toFloat()
          pts.add(Pair(cx + rx * cos(theta), cy + ry * sin(theta)))
        }
        contours.add(pts)
      }

      ShapeType.STAR -> {
        val cx = x + w / 2f
        val cy = y + h / 2f
        val rOuter = min(w, h) / 2f
        val rInner = rOuter * 0.45f
        val points = shape.polygonPoints.coerceAtLeast(3) * 2
        val pts = mutableListOf<Pair<Float, Float>>()
        for (i in 0..points) {
          val r = if (i % 2 == 0) rOuter else rInner
          val theta = (-PI.toFloat() / 2f) + (2 * PI.toFloat() * i / points)
          pts.add(Pair(cx + r * cos(theta), cy + r * sin(theta)))
        }
        contours.add(pts)
      }

      ShapeType.FRAME -> {
        // Outer border
        contours.add(listOf(
          Pair(x, y),
          Pair(x + w, y),
          Pair(x + w, y + h),
          Pair(x, y + h),
          Pair(x, y)
        ))
        // Inner cutout border
        val inset = min(w, h) * 0.12f
        contours.add(listOf(
          Pair(x + inset, y + inset),
          Pair(x + w - inset, y + inset),
          Pair(x + w - inset, y + h - inset),
          Pair(x + inset, y + h - inset),
          Pair(x + inset, y + inset)
        ))
      }

      ShapeType.LIVING_HINGE -> {
        // Outer perimeter
        contours.add(listOf(
          Pair(x, y),
          Pair(x + w, y),
          Pair(x + w, y + h),
          Pair(x, y + h),
          Pair(x, y)
        ))
        // Alternating flex cut lines inside
        val numCuts = 12
        val slotSpacing = w / (numCuts + 1)
        for (i in 1..numCuts) {
          val sx = x + i * slotSpacing
          if (i % 2 == 0) {
            contours.add(listOf(Pair(sx, y + 4f), Pair(sx, y + h - 8f)))
          } else {
            contours.add(listOf(Pair(sx, y + 8f), Pair(sx, y + h - 4f)))
          }
        }
      }

      ShapeType.CALIBRATION_GRID -> {
        // Outer grid border
        contours.add(listOf(
          Pair(x, y),
          Pair(x + w, y),
          Pair(x + w, y + h),
          Pair(x, y + h),
          Pair(x, y)
        ))
        // 4x4 matrix test cells
        val cols = 4
        val rows = 4
        val cellW = (w - 10f) / cols
        val cellH = (h - 10f) / rows
        for (r in 0 until rows) {
          for (c in 0 until cols) {
            val cx = x + 5f + c * cellW
            val cy = y + 5f + r * cellH
            contours.add(listOf(
              Pair(cx + 1f, cy + 1f),
              Pair(cx + cellW - 1f, cy + 1f),
              Pair(cx + cellW - 1f, cy + cellH - 1f),
              Pair(cx + 1f, cy + cellH - 1f),
              Pair(cx + 1f, cy + 1f)
            ))
          }
        }
      }

      ShapeType.TEXT -> {
        // Text vector stroke paths (simulated single-line laser text font)
        contours.addAll(generateTextStrokeContours(shape.text.ifEmpty { "LIGHTBURN" }, x, y, w, h))
      }
    }

    return contours
  }

  data class Scanline(val startX: Float, val startY: Float, val endX: Float, val endY: Float)

  /**
   * Generates raster scanlines for fill engraving
   */
  private fun generateRasterScanlines(shape: LaserShape, lineIntervalMm: Double): List<Scanline> {
    val interval = lineIntervalMm.toFloat().coerceIn(0.04f, 1.0f)
    // For fast simulation preview, cap total scanlines to 40 max
    val step = max(interval * 4f, shape.height / 35f)
    val lines = mutableListOf<Scanline>()
    var y = shape.y + 0.5f
    var leftToRight = true

    while (y <= shape.y + shape.height) {
      val x1 = shape.x + 0.5f
      val x2 = shape.x + shape.width - 0.5f

      if (leftToRight) {
        lines.add(Scanline(x1, y, x2, y))
      } else {
        lines.add(Scanline(x2, y, x1, y))
      }
      leftToRight = !leftToRight
      y += step
    }
    return lines
  }

  /**
   * Concentric offset contours for offset fill
   */
  private fun generateOffsetContours(shape: LaserShape, steps: Int): List<List<Pair<Float, Float>>> {
    val result = mutableListOf<List<Pair<Float, Float>>>()
    val delta = min(shape.width, shape.height) / (steps * 2.5f)
    for (i in 0 until steps) {
      val inset = i * delta
      val x1 = shape.x + inset
      val y1 = shape.y + inset
      val x2 = shape.x + shape.width - inset
      val y2 = shape.y + shape.height - inset
      if (x2 > x1 && y2 > y1) {
        result.add(listOf(
          Pair(x1, y1),
          Pair(x2, y1),
          Pair(x2, y2),
          Pair(x1, y2),
          Pair(x1, y1)
        ))
      }
    }
    return result
  }

  /**
   * Simplified vector Hershey-style stroke generator for laser engraved text
   */
  private fun generateTextStrokeContours(text: String, x: Float, y: Float, w: Float, h: Float): List<List<Pair<Float, Float>>> {
    val contours = mutableListOf<List<Pair<Float, Float>>>()
    val charCount = text.length.coerceAtLeast(1)
    val charWidth = w / charCount
    val charHeight = h

    text.forEachIndexed { index, ch ->
      val cx = x + index * charWidth
      val cy = y
      val cw = charWidth * 0.85f
      val chH = charHeight

      when (ch.uppercaseChar()) {
        'L' -> contours.add(listOf(Pair(cx, cy), Pair(cx, cy + chH), Pair(cx + cw, cy + chH)))
        'I' -> contours.add(listOf(Pair(cx + cw / 2f, cy), Pair(cx + cw / 2f, cy + chH)))
        'G' -> contours.add(listOf(Pair(cx + cw, cy), Pair(cx, cy), Pair(cx, cy + chH), Pair(cx + cw, cy + chH), Pair(cx + cw, cy + chH * 0.5f), Pair(cx + cw * 0.5f, cy + chH * 0.5f)))
        'H' -> {
          contours.add(listOf(Pair(cx, cy), Pair(cx, cy + chH)))
          contours.add(listOf(Pair(cx + cw, cy), Pair(cx + cw, cy + chH)))
          contours.add(listOf(Pair(cx, cy + chH / 2f), Pair(cx + cw, cy + chH / 2f)))
        }
        'T' -> {
          contours.add(listOf(Pair(cx, cy), Pair(cx + cw, cy)))
          contours.add(listOf(Pair(cx + cw / 2f, cy), Pair(cx + cw / 2f, cy + chH)))
        }
        'B' -> {
          contours.add(listOf(Pair(cx, cy), Pair(cx, cy + chH), Pair(cx + cw * 0.8f, cy + chH), Pair(cx + cw, cy + chH * 0.75f), Pair(cx, cy + chH * 0.5f), Pair(cx + cw * 0.8f, cy + chH * 0.5f), Pair(cx + cw, cy + chH * 0.25f), Pair(cx, cy)))
        }
        'U' -> contours.add(listOf(Pair(cx, cy), Pair(cx, cy + chH), Pair(cx + cw, cy + chH), Pair(cx + cw, cy)))
        'R' -> {
          contours.add(listOf(Pair(cx, cy + chH), Pair(cx, cy), Pair(cx + cw, cy), Pair(cx + cw, cy + chH * 0.5f), Pair(cx, cy + chH * 0.5f)))
          contours.add(listOf(Pair(cx + cw * 0.4f, cy + chH * 0.5f), Pair(cx + cw, cy + chH)))
        }
        'N' -> contours.add(listOf(Pair(cx, cy + chH), Pair(cx, cy), Pair(cx + cw, cy + chH), Pair(cx + cw, cy)))
        'A' -> {
          contours.add(listOf(Pair(cx, cy + chH), Pair(cx + cw / 2f, cy), Pair(cx + cw, cy + chH)))
          contours.add(listOf(Pair(cx + cw * 0.25f, cy + chH * 0.6f), Pair(cx + cw * 0.75f, cy + chH * 0.6f)))
        }
        'O', '0' -> contours.add(listOf(Pair(cx, cy), Pair(cx + cw, cy), Pair(cx + cw, cy + chH), Pair(cx, cy + chH), Pair(cx, cy)))
        else -> {
          // Default bounding box for other chars
          contours.add(listOf(Pair(cx, cy), Pair(cx + cw, cy), Pair(cx + cw, cy + chH), Pair(cx, cy + chH), Pair(cx, cy)))
        }
      }
    }
    return contours
  }
